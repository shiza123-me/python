v1=float(input("Enter V1: "))
v2=float(input("Enter V2: "))
operator=input("Enter Operator (+, -, *, /): ")
if operator=='+':
    print("Result: ", v1+v2)
elif operator=='-':
    print("Result: ", v1-v2)
elif operator=='*':
    print("Result: ", v1*v2)
elif operator=='/':
    print("Result: ", v1/v2)